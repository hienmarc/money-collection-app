CREATE TABLE public.wishlist (
    wishlistid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ownerid uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    numistaid integer NOT NULL,
    min_year integer,
    max_year integer,
    title text NOT NULL,
    country text NOT NULL,
    obverse_thumbnail text,
    level integer NOT NULL CHECK (level BETWEEN 1 AND 5),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT wishlist_owner_numistaid_key UNIQUE (ownerid, numistaid)
);

ALTER TABLE public.wishlist ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.wishlist FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.wishlist_wishlistid_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.wishlist TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.wishlist TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.wishlist_wishlistid_seq TO authenticated;

CREATE POLICY "Wishlist is viewable by owner or public profile visitors"
    ON public.wishlist
    FOR SELECT
    USING (
        ownerid = auth.uid()
        OR EXISTS (
            SELECT 1
            FROM public.profiles
            WHERE profiles.id = wishlist.ownerid
              AND profiles.is_public = true
        )
    );

CREATE POLICY "Users can insert own wishlist entries"
    ON public.wishlist
    FOR INSERT
    TO authenticated
    WITH CHECK (ownerid = auth.uid());

CREATE POLICY "Users can update own wishlist entries"
    ON public.wishlist
    FOR UPDATE
    TO authenticated
    USING (ownerid = auth.uid())
    WITH CHECK (ownerid = auth.uid());

CREATE POLICY "Users can delete own wishlist entries"
    ON public.wishlist
    FOR DELETE
    TO authenticated
    USING (ownerid = auth.uid());
